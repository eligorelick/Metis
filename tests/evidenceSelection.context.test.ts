import { describe, expect, it } from "vitest";
import { selectEventLifecycleEvidence, selectMaterialEvidence, type EvidenceProfile } from "@/pipeline/stageC/evidenceSelection";

const crowd = Array.from({ length: 100 }, (_, i) => `Revenue and operating income for region ${i} were $90 million and $20 million, up 35% and 40%; liquidity included $50 million of cash.`).join(" ");
function select(body: string, budget = 3_000, profile: EvidenceProfile = "interim") {
  const source = `${crowd}\n${body}\n${crowd}`;
  const result = selectMaterialEvidence(source, budget, profile);
  expect(result.text.length).toBeLessThanOrEqual(budget);
  let end = 0;
  for (const span of result.spans) {
    expect(span.start).toBeGreaterThanOrEqual(end);
    expect(source.slice(span.start, span.end)).toBe(span.text);
    expect(result.text).toContain(span.text);
    end = span.end;
  }
  expect(result.coverage.retainedChars + result.coverage.omittedChars).toBe(source.length);
  return result.text;
}

describe("qualifying filing context (R8)", () => {
  const kpi = "Key operating metrics Three Months Ended June 30, 2026 2025 (In thousands, except percentages) Marketplace volume (A) $ 4,200,000 $ 1,800,000 Net take rate (G) 3.6 % 4.0 % Adjusted revenue $ 218,000 $ 112,000";
  const definition = "(G) Net Take Rate is derived from selected loan-related revenue. These items represent revenue generated by the marketplace. Valuation changes in servicing rights and marketing expenses are deducted. This net amount is divided by marketplace volume for that period.";
  it("keeps a selected KPI table with its complete referenced definition, deductions and denominator", () => {
    const text = select(`${kpi} _______________ (A) We define marketplace volume as originated loans. ${definition} (H) See the non-GAAP reconciliation.`, 2_000);
    expect(text).toContain(kpi);
    expect(text).toContain(definition);
  });
  it("withholds the KPI values when their definition cannot fit", () => {
    const text = select(`${kpi} _______________ ${definition}`, 500);
    expect(text).not.toContain("3.6 % 4.0 %");
  });
  it("keeps the other referenced KPI footnotes, not just the definition lead", () => {
    const a = "(A) Marketplace volume consists of originations and resales.";
    const g = "(G) Net Take Rate is derived from selected revenue. Marketing expenses are deducted. This net amount is divided by marketplace volume.";
    const text = select(`${kpi} _______________ ${a} ${g}`, 2_000);
    expect(text).toContain(a);
    expect(text).toContain(g);
  });
  it("keeps subsequent definition changes and retrospective application together", () => {
    const change = "(A) The Company added valuation changes to its definition of Adjusted EBITDA effective March 31, 2026. Additionally, acquisition-related costs were added to the definition effective June 30, 2026. These adjustments have been applied retrospectively to all periods presented.";
    expect(select(change, 1_000)).toContain(change);
  });
  it("does not make a definition-change footnote depend on an oversized reconciliation table", () => {
    const table = `Adjusted EBITDA reconciliation (In thousands) Adjustments (A) ${"Net income $ 100 200 Interest $ 20 30 ".repeat(70)}`;
    const change = "(A) The Company added marketable-security valuation changes to its definition of Adjusted EBITDA effective March 31, 2026. Additionally, acquisition-related costs were added to the definition effective June 30, 2026. These adjustments have been applied retrospectively to all periods presented.";
    expect(select(`${table} ${change}`, 1_300)).toContain(change);
  });
  it("keeps inline numbered financing clauses as one sentence or omits the whole sentence", () => {
    const closing = "In connection with the closing, (1) the Company repaid in full all outstanding obligations under the Credit Agreement with First Bank, and (2) Harbor Funding, Inc. terminated the Master Repurchase Agreement with Second Bank.";
    const text = selectMaterialEvidence(`On September 1, 2026, Example, Inc. completed the acquisition. ${closing} ${crowd}`, 400, "event").text;
    expect(text.includes("repaid in full")).toBe(text.includes("Second Bank"));
  });
  it("does not treat a conditional termination as an actual facility closure", () => {
    const hypothetical = "If the merger agreement is terminated, the Company may be required to pay a $25 million termination fee.";
    expect(selectEventLifecycleEvidence(`${hypothetical} ${crowd}`, 1_200, [])).toBeNull();
  });
  it("keeps omitted financing status in a bounded supplement and does not repeat complete status", () => {
    const status = "In connection with the closing, (1) the Company repaid in full the Credit Agreement with First Bank, and (2) Harbor Funding, Inc. terminated the Master Repurchase Agreement with Second Bank. Upon such repayment and termination, all liens were released.";
    const source = `On September 1, 2026, Example, Inc. acquired Harbor. ${status} ${crowd}`;
    const supplement = selectEventLifecycleEvidence(source, 1_200, []);
    expect(supplement?.text).toContain(status);
    expect(supplement!.text.length).toBeLessThanOrEqual(1_200);
    for (const span of supplement!.spans) expect(source.slice(span.start, span.end)).toBe(span.text);
    expect(selectEventLifecycleEvidence(source, 1_200, supplement!.spans)).toBeNull();
    expect(selectEventLifecycleEvidence(source, 200, [])).toBeNull();
  });
  it("keeps a debt commitment's unused and terminated status", () => {
    const debt = "The Company entered into a commitment for a $600 million 364-day bridge loan facility. As of June 30, 2026, there were no outstanding borrowings under the bridge loan facility. Following issuance of the senior notes, the Company terminated the bridge loan facility effective July 14, 2026. Prior to its termination, there were no borrowings and no early termination penalties.";
    expect(select(debt, 1_600, "notes")).toContain(debt);
  });
  it("keeps historical warehouse terms with their deconsolidation qualifier", () => {
    const debt = "The REIT Warehouse bears interest at SOFR plus a spread of 3.00% or 3.50%. The warehouse was the facility for Example REIT, Inc. As of March 27, 2026, Example REIT, Inc. merged into Evergreen LP. As a result of the merger, Example REIT, Inc. is no longer controlled nor consolidated by the Company.";
    expect(select(debt, 1_600, "notes")).toContain(debt);
  });
  it("does not retain historical debt terms alone when their lifecycle context cannot fit", () => {
    const debt = "The warehouse facility bears interest at SOFR plus 3.00%. As a result of the merger, the subsidiary is no longer controlled nor consolidated by the Company.";
    expect(select(debt, 300, "notes")).not.toContain("SOFR plus 3.00%");
  });
  it("keeps closing repayments and facility terminations ahead of agreement boilerplate", () => {
    const closing = "In connection with the closing, the Company repaid all outstanding obligations under the acquired Credit Agreement with First Bank and terminated the Master Repurchase Agreement with Second Bank. Upon such repayment and termination, all liens were released.";
    const text = selectMaterialEvidence(`On September 1, 2026, Example, Inc. completed the acquisition. The Company paid $590 million in cash. ${closing} ${crowd}`, 1_200, "event").text;
    expect(text).toContain(closing);
    expect(text).toContain("$590 million");
  });
  it("keeps the complete related-party debt component table with dates and units", () => {
    const table = "NOTE 6 — DEBT The following table summarizes debt components (dollars in thousands): June 30, 2026 December 31, 2025 Debt at fair value to related parties: Certificates 118,293 2,050 Lending liabilities 306,347 164,085 Total related-party debt 424,640 166,135 Total debt $ 962,995 $ 557,237";
    expect(select(`${table} (A) Debt obligations were extended or repaid.`, 1_400, "notes")).toContain(table);
  });
  it("keeps a named counterparty's related-party debt classification", () => {
    const relationship = "Harbor Ltd. holds certificates as part of its protocol activity; these holdings are recorded in Debt, current to related parties in the consolidated balance sheets.";
    expect(select(relationship, 900, "notes")).toContain(relationship);
  });
  const sensitivity = "Significant Valuation Input Sensitivity The following tables summarize the estimated change in fair value for Level 3 assets at June 30, 2026. Each analysis is hypothetical and illustrative. The assumptions are stressed independently, and results do not reflect adjustments for the Company's ownership share. (dollars in tables in thousands) -2% -1% +1% +2% $ % $ % $ % Discount rate: Servicing assets: HELOC loans 9,109 6.3 4,425 3.1 ( 4,165 ) ( 2.9 ) ( 8,100 ) ( 5.6 ) Loans held for sale: HELOC loans 12,914 2.5 10,499 2.0 ( 16,100 ) ( 3.1 ) ( 32,163 ) ( 6.2 )";
  it("keeps a quantitative valuation-sensitivity table, its shock headers, units and limitations", () => {
    expect(select(`${sensitivity}\nMarketable Securities\nThe following table summarizes investments.`, 2_000, "notes")).toContain(sensitivity);
  });
  it("withholds a sensitivity table when its scope and limitations cannot fit", () => {
    expect(select(sensitivity, 600, "notes")).not.toContain("( 4,165 )");
  });
  it("keeps the cause of a material expense increase with the change", () => {
    const driver = "General and administrative expense increased $35.0 million, or 213.6%. This primarily consisted of an increase in stock-based compensation expense of $21.8 million, due to awards satisfying the IPO liquidity condition, IPO-related grants, and increased grants from headcount growth.";
    expect(select(driver, 1_200)).toContain(driver);
  });
  it("keeps the component table and disposal explanation for an aggregate income line", () => {
    const table = "Other income (expense), net Three Months Ended June 30 (In thousands) 2026 2025 Digital-asset valuation $ (870) $ 2,064 Fund changes (116) — Staking and realized gains 718 2,314 Other 5,519 1,249 Total other income (expense), net $ 5,251 $ 5,627";
    const cause = "Other income (expense), net decreased $0.4 million, primarily driven by digital-asset losses, offset by a $5.9 million gain on the disposal of an equity-method investment.";
    expect(select(`${table} ${cause}`, 1_600)).toContain(`${table} ${cause}`);
  });
  it("keeps cash held for third parties alongside headline liquidity evidence", () => {
    const cash = "As part of its servicing operations, the Company held borrower payments of $487.5 million due to third-party loan buyers recorded in Payables to third-party loan owners.";
    expect(select(cash, 900, "notes")).toContain(cash);
  });
  it("keeps dated unused program capacity ahead of crowded operating figures", () => {
    const capacity = "As of June 30, 2026, the Company repurchased no shares and has $200.0 million remaining authorized under the repurchase program.";
    expect(select(capacity, 900)).toContain(capacity);
  });
  // Integration of R8 (FIGR extra-high audit): atomic tables never take a family's turn, so the
  // MD&A results table (gain on sale of loans, gain on servicing asset) and the non-GAAP
  // reconciliation fell behind the qualifying contexts; the old chunks had carried them.
  const results = "Results of Operations Condensed Consolidated Statements of Operations The following table sets forth our results for the periods presented: Three Months Ended June 30, (In thousands) 2026 2025 Revenue: Ecosystem and technology fees $ 72,858 $ 28,140 Gain on sale of loans, net 57,572 36,312 Gain on servicing asset, net 29,093 1,844 Interest income 22,809 11,966 Net revenue 225,588 106,077 Operating income 77,935 27,632";
  it("keeps the MD&A results-of-operations table ahead of the qualifying contexts", () => {
    const capacity = "As of June 30, 2026, the Company repurchased no shares and has $200.0 million remaining authorized under the repurchase program.";
    const text = select(`${results}\n${capacity} ${definition}`, 1_400);
    expect(text).toContain(results);
  });
  it("keeps a primary table's continuation rows with its head", () => {
    const head = "The following table presents a reconciliation of net income to adjusted EBITDA: Three Months Ended June 30, (In thousands) 2026 2025 Net income $ 87,436 $ 29,994 Adjusted for: Valuation changes in fair value of servicing asset (8,395) 5,848 Stock-based compensation 26,098 8,113 Total adjustments 31,943 22,872.";
    const rows = "(30) Adjusted EBITDA $ 119,379 $ 52,866 Net income margin 38.8 % 28.3 %";
    const text = select(`${head} ${rows}`, 2_000);
    expect(text).toContain(`${head} ${rows}`);
  });
  it("leaves the results table to the filler in a notes excerpt", () => {
    expect(selectMaterialEvidence(`${crowd}\n${results}\n${crowd}`, 1_400, "notes").text).not.toContain("Gain on sale of loans, net 57,572");
  });
  it.each([0, 50, 210, 500, 2_000])("is deterministic and stays within a %i-character budget", (budget) => {
    const source = `${crowd} ${sensitivity} ${definition}`;
    expect(selectMaterialEvidence(source, budget, "notes")).toEqual(selectMaterialEvidence(source, budget, "notes"));
    expect(selectMaterialEvidence(source, budget, "notes").text.length).toBeLessThanOrEqual(budget);
  });
});
